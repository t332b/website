#!/usr/bin/env node
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');

const publicMusicDir = path.join(projectRoot, 'public', 'music');
const tracksDir = path.join(projectRoot, 'src', 'content', 'tracks');
const worksDir = path.join(projectRoot, 'src', 'content', 'works');
const outDir = path.join(projectRoot, 'src', 'data');
const outFile = path.join(outDir, 'musicList.generated.ts');

function ensureDirSync(dir) {
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
}

function listMp3Slugs() {
  if (!fs.existsSync(publicMusicDir)) return [];
  const files = fs.readdirSync(publicMusicDir, { withFileTypes: true });
  return files
    .filter((d) => d.isFile() && /\.mp3$/i.test(d.name))
    .map((d) => d.name.replace(/\.mp3$/i, ''))
    .sort((a, b) => a.localeCompare(b));
}

function readFrontmatter(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const raw = fs.readFileSync(filePath, 'utf8');
  const m = raw.match(/^---\n([\s\S]*?)\n---/);
  if (!m) return {};
  const fm = {};
  const lines = m[1].split(/\r?\n/);
  for (const line of lines) {
    const kv = line.match(/^([a-zA-Z0-9_]+):\s*(.*)$/);
    if (kv) {
      const key = kv[1].trim();
      let val = kv[2].trim();
      // strip quotes
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        val = val.slice(1, -1);
      }
      fm[key] = val;
    }
  }
  return fm;
}

function buildWorksIdToCover() {
  const map = new Map(); // id -> cover
  if (!fs.existsSync(worksDir)) return map;
  const files = fs.readdirSync(worksDir).filter((f) => f.endsWith('.mdx'));
  for (const f of files) {
    const p = path.join(worksDir, f);
    const raw = fs.readFileSync(p, 'utf8');
    const m = raw.match(/^---\n([\s\S]*?)\n---/);
    if (!m) continue;
    const block = m[1];
    const idMatch = block.match(/^id:\s*(.*)$/m);
    const coverListMatch = block.match(/^cover_url_list:\s*\n([\s\S]*?)(?=\n[A-Za-z_]|$)/m);
    let cover;
    if (coverListMatch) {
      const listBlock = coverListMatch[1];
      const firstUrl = (listBlock.match(/-\s*(.*)\s*$/m) || [])[1];
      if (firstUrl) {
        cover = firstUrl.replace(/^"|"$/g, '').replace(/^'|'$/g, '');
      }
    }
    const idLine = idMatch ? idMatch[1].trim().replace(/^"|"$/g, '').replace(/^'|'$/g, '') : null;
    if (idLine && cover) {
      map.set(idLine, cover);
    }
  }
  return map;
}

function getReleaseIdForSlug(slug) {
  const trackFile = path.join(tracksDir, `${slug}.mdx`);
  if (!fs.existsSync(trackFile)) return null;
  const fm = readFrontmatter(trackFile);
  return fm['release_id'] || null;
}

function generate(items) {
  const header = `// AUTO-GENERATED FILE. Do not edit.\n// Generated by scripts/generate-music-list.mjs\n`;
  const body = `export type MusicItem = { slug: string; src: string; cover?: string };\nexport const musicItems: MusicItem[] = ${JSON.stringify(items, null, 2)};\n`;
  return header + body;
}

function main() {
  const slugs = listMp3Slugs();
  const idToCover = buildWorksIdToCover();
  const items = slugs.map((slug) => {
    const relId = getReleaseIdForSlug(slug);
    const cover = relId ? idToCover.get(relId) : undefined;
    return { slug, src: `/music/${slug}.mp3`, cover };
  });
  ensureDirSync(outDir);
  fs.writeFileSync(outFile, generate(items), 'utf8');
  console.log(`[music] Found ${slugs.length} tracks -> ${path.relative(projectRoot, outFile)}`);
}

main();
